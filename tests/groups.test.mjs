import test from 'node:test';import assert from 'node:assert/strict';
import {createNamedGroup,renameNamedGroup,moveToGroup,removeNamedGroup} from '../src/core/groups.mjs';
test('groups can be created empty; no auto grouping by fixture label',()=>{
 const groups=createNamedGroup([],'Stage A');
 assert.deepEqual(groups,['Stage A']);assert.throws(()=>createNamedGroup(groups,'Stage A'));
 assert.throws(()=>createNamedGroup([],'UNGROUPED'));
});
test('renaming a group moves every member including locked fixtures',()=>{
 const fs=[{id:'1',group:'Old',locked:true},{id:'2',group:'Old'},{id:'3',group:''}];
 const r=renameNamedGroup(['Old','Free'],fs,'Old','Truss');
 assert.deepEqual(r.groups,['Truss','Free']);
 assert.deepEqual(r.fixtures.map(f=>f.group),['Truss','Truss','']);
});
test('manual move supports multi-select and ungroup; rejects nonexistent groups',()=>{
 const fs=[{id:'1',group:''},{id:'2',group:''}];
 assert.deepEqual(moveToGroup(fs,['1','2'],'Truss',['Truss']).map(f=>f.group),['Truss','Truss']);
 assert.deepEqual(moveToGroup(fs,['1'],'',[]).map(f=>f.group),['','']);
 assert.throws(()=>moveToGroup(fs,['1'],'AutoGenerated',[]),RangeError);
});
test('delete group ungroups its members but does not delete fixtures',()=>{
 const fs=[{id:'1',group:'Truss'},{id:'2',group:'Other'}];
 const r=removeNamedGroup(['Truss','Other'],fs,'Truss');
 assert.deepEqual(r.groups,['Other']);assert.equal(r.fixtures[0].group,'');assert.equal(r.fixtures.length,2);
});
